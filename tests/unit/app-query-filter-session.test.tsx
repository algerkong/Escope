import { fireEvent, screen, waitFor, within } from '@testing-library/react';
import { describe, expect, it } from 'vitest';
import { DATA_PREVIEW_DSL } from '../../src/domain/query-pagination';
import { i18n } from '../../src/locales';
import { enQueryFilters } from '../../src/locales/query-filters';
import { add, apply, applyStatusFilter, fixture, preview } from './query-filter-workspace-fixture';

describe('applied filter bindings in the workspace', () => {
  it('re-enables without wrapper growth, freezes new executions independently, and stores only applied DSL and original metadata', async () => {
    const f = await fixture(true, false, true, true);
    f.mount();
    await f.saved();
    const final = await applyStatusFilter(f);
    const executed = f.backend.execute.mock.calls[0]![0].rawDsl;
    expect(screen.getByRole('group', { name: '1 session filters' })).toHaveTextContent('1 / 1 enabled');
    fireEvent.click(screen.getByRole('button', { name: 'Edit session filters' }));
    preview();
    expect(screen.getByRole('button', { name: 'Apply filters to draft' })).toBeDisabled();
    await f.user.keyboard('{Escape}');
    expect(screen.queryByRole('group', { name: '1 pending filters' })).not.toBeInTheDocument();
    expect(screen.getByRole('button', { name: 'Run query' })).toBeEnabled();
    fireEvent.click(screen.getByRole('button', { name: 'Edit session filters' }));
    fireEvent.click(screen.getByRole('switch', { name: 'Filter enabled for status' }));
    preview();
    expect(screen.getByLabelText('Final filtered DSL')).toHaveValue(f.query.dsl);
    apply();
    expect(screen.getByLabelText('Query DSL')).toHaveValue(f.query.dsl);
    expect(screen.getByRole('group', { name: '1 session filters' })).toHaveTextContent('0 / 1 enabled');
    expect(f.backend.execute).toHaveBeenCalledTimes(1);
    fireEvent.click(screen.getByRole('button', { name: 'Run query' }));
    await waitFor(() => expect(f.backend.execute).toHaveBeenCalledTimes(2));
    await waitFor(() => expect(screen.getByRole('button', { name: 'Run query' })).toBeEnabled());
    expect(JSON.parse(f.backend.execute.mock.calls[1]![0].rawDsl).query.bool.must).toEqual(JSON.parse(f.query.dsl).query.bool.must);
    fireEvent.click(screen.getByRole('button', { name: 'Edit session filters' }));
    fireEvent.click(screen.getByRole('switch', { name: 'Filter enabled for status' }));
    preview();
    expect(screen.getByLabelText('Final filtered DSL')).toHaveValue(final);
    apply();
    expect(f.backend.execute).toHaveBeenCalledTimes(2);
    expect(f.backend.execute.mock.calls[0]![0].rawDsl).toBe(executed);
    await f.saved();
    const stored = (await f.recovery.load()).document;
    expect(stored.workspace!.tabs[0]!.document).toMatchObject({ dsl: final, parameters: f.query.parameters, timeRange: f.query.timeRange });
    expect(stored.workspace!.tabs[0]!.document).not.toHaveProperty('binding');
    expect(stored.workspace!.tabs[0]!.document).not.toHaveProperty('baseline');
    expect(stored.history.every((entry) => !Object.hasOwn(entry.snapshot, 'binding'))).toBe(true);
  });

  it('supports a new query binding before its first execution and after the originating index closes', async () => {
    const f = await fixture();
    f.mount();
    await f.saved();
    fireEvent.click(await screen.findByRole('button', { name: 'events' }));
    await screen.findByText('ready', { selector: '.rg-cell' });
    f.clickCell('ready', 'status');
    await waitFor(() => expect(screen.getByRole('button', { name: 'Add to pending filters' })).toBeEnabled());
    add();
    preview();
    const final = (screen.getByLabelText('Final filtered DSL') as HTMLTextAreaElement).value;
    fireEvent.click(screen.getByRole('button', { name: 'Open filtered query' }));
    expect(screen.getByRole('group', { name: '1 session filters' })).toBeVisible();
    fireEvent.click(screen.getByRole('button', { name: 'Edit session filters' }));
    fireEvent.click(screen.getByRole('switch', { name: 'Filter enabled for status' }));
    preview();
    expect(screen.getByLabelText('Final filtered DSL')).toHaveValue(DATA_PREVIEW_DSL);
    apply();
    expect(screen.getByLabelText('Query DSL')).toHaveValue(DATA_PREVIEW_DSL);
    fireEvent.click(screen.getByRole('button', { name: i18n.t('queryLive:closeIndex', { index: 'events', connection: 'Alpha' }) }));
    expect(screen.queryByRole('tab', { name: 'events (Alpha)' })).not.toBeInTheDocument();
    fireEvent.click(screen.getByRole('button', { name: 'Edit session filters' }));
    fireEvent.click(screen.getByRole('switch', { name: 'Filter enabled for status' }));
    preview();
    expect(screen.getByLabelText('Final filtered DSL')).toHaveValue(final);
    apply();
    expect(screen.getByLabelText('Query DSL')).toHaveValue(final);
    expect(screen.getByRole('heading', { name: i18n.t('query:noResults') })).toBeVisible();
    expect(f.backend.execute).toHaveBeenCalledTimes(1);
    await f.saved();
  });

  it('keeps later manual edits intact, blocks old-baseline review and confirms detaching without changing DSL or results', async () => {
    const f = await fixture();
    f.mount();
    await f.saved();
    const final = await applyStatusFilter(f);
    const changed = final.replace('"size": 25', '"size": 7');
    fireEvent.change(screen.getByLabelText('Query DSL'), { target: { value: changed } });
    expect(screen.getByRole('group', { name: '1 session filters' })).toHaveTextContent(enQueryFilters.filterBindingChanged);
    fireEvent.click(screen.getByRole('button', { name: 'Edit session filters' }));
    expect(screen.getByRole('alert')).toHaveTextContent(enQueryFilters.filterBindingChanged);
    expect(screen.getByRole('switch', { name: 'Filter enabled for status' })).toBeDisabled();
    expect(screen.getByRole('button', { name: 'Preview filtered DSL' })).toBeDisabled();
    expect(screen.getByRole('button', { name: 'Remove filter for status' })).toBeDisabled();
    await f.user.keyboard('{Escape}');
    expect(screen.getByLabelText('Query DSL')).toHaveValue(changed);
    fireEvent.click(screen.getByRole('button', { name: 'Detach session filters' }));
    let dialog = screen.getByRole('dialog', { name: 'Detach session filters?' });
    expect(dialog).toHaveTextContent('Current DSL and results stay unchanged.');
    fireEvent.click(within(dialog).getByRole('button', { name: 'Cancel' }));
    expect(screen.getByRole('group', { name: '1 session filters' })).toBeVisible();
    fireEvent.click(screen.getByRole('button', { name: 'Detach session filters' }));
    dialog = screen.getByRole('dialog', { name: 'Detach session filters?' });
    fireEvent.click(within(dialog).getByRole('button', { name: 'Detach session filters' }));
    expect(screen.queryByRole('group', { name: '1 session filters' })).not.toBeInTheDocument();
    expect(screen.getByLabelText('Query DSL')).toHaveValue(changed);
    expect(screen.getByText('ready', { selector: '.rg-cell' })).toBeVisible();
    expect(f.backend.execute).toHaveBeenCalledTimes(1);
    await f.saved();
  });

  it('retains applied and pending copies separately across settings, connections and cancelling an edit', async () => {
    const f = await fixture();
    f.mount();
    await f.saved();
    const final = await applyStatusFilter(f);
    fireEvent.click(screen.getByRole('button', { name: 'Edit session filters' }));
    fireEvent.click(screen.getByRole('switch', { name: 'Filter enabled for status' }));
    await f.user.keyboard('{Escape}');
    expect(screen.getByRole('group', { name: '1 pending filters' })).toHaveTextContent('0 / 1 enabled');
    expect(screen.getByRole('button', { name: 'Run query' })).toBeDisabled();
    expect(screen.getByRole('button', { name: 'Save draft' })).toBeDisabled();
    await f.user.click(screen.getAllByRole('button', { name: 'Settings' })[0]!);
    await f.user.click(screen.getByRole('button', { name: 'Back to query' }));
    await f.user.selectOptions(screen.getByLabelText('Active connection'), f.b.id);
    await f.user.selectOptions(screen.getByLabelText('Active connection'), f.a.id);
    await f.user.click(screen.getByRole('tab', { name: 'Filter draft' }));
    fireEvent.click(screen.getByRole('button', { name: 'Review pending filters' }));
    expect(screen.getByRole('switch', { name: 'Filter enabled for status' })).not.toBeChecked();
    fireEvent.click(screen.getByRole('button', { name: 'Discard pending filters' }));
    expect(screen.getByRole('group', { name: '1 session filters' })).toHaveTextContent('1 / 1 enabled');
    expect(screen.getByLabelText('Query DSL')).toHaveValue(final);
    expect(screen.getByRole('button', { name: 'Run query' })).toBeEnabled();
    expect(f.backend.execute).toHaveBeenCalledTimes(1);
    await f.saved();
  });

  it('can disable a known binding after a failed rerun without treating that execution as successful evidence', async () => {
    const f = await fixture();
    f.mount();
    await f.saved();
    await applyStatusFilter(f);
    f.backend.execute.mockRejectedValueOnce({ code: 'forbidden' });
    fireEvent.click(screen.getByRole('button', { name: 'Run query' }));
    await waitFor(() => expect(f.backend.execute).toHaveBeenCalledTimes(2));
    await waitFor(() => expect(screen.getByRole('button', { name: 'Run query' })).toBeEnabled());
    fireEvent.click(screen.getByRole('button', { name: 'Edit session filters' }));
    fireEvent.click(screen.getByRole('switch', { name: 'Filter enabled for status' }));
    preview();
    expect(screen.getByLabelText('Final filtered DSL')).toHaveValue(f.query.dsl);
    apply();
    expect(screen.getByRole('group', { name: '1 session filters' })).toHaveTextContent('0 / 1 enabled');
    expect(screen.getByLabelText('Query DSL')).toHaveValue(f.query.dsl);
    expect(f.backend.execute).toHaveBeenCalledTimes(2);
    await f.saved();
    expect((await f.recovery.load()).document.history.filter((entry) => entry.status === 'failed')).toHaveLength(1);
  });

  it('keeps an empty removal draft blocking until explicitly applied, while cancellation preserves the applied binding', async () => {
    const f = await fixture();
    f.mount();
    await f.saved();
    const final = await applyStatusFilter(f);
    fireEvent.click(screen.getByRole('button', { name: 'Edit session filters' }));
    fireEvent.click(screen.getByRole('button', { name: 'Remove filter for status' }));
    await f.user.keyboard('{Escape}');
    expect(screen.getByRole('group', { name: '0 pending filters' })).toBeVisible();
    expect(screen.getByRole('button', { name: 'Run query' })).toBeDisabled();
    expect(screen.getByRole('button', { name: 'Save draft' })).toBeDisabled();
    fireEvent.click(screen.getByRole('button', { name: 'Discard pending filters' }));
    expect(screen.getByRole('group', { name: '1 session filters' })).toBeVisible();
    expect(screen.getByLabelText('Query DSL')).toHaveValue(final);
    fireEvent.click(screen.getByRole('button', { name: 'Edit session filters' }));
    fireEvent.click(screen.getByRole('button', { name: 'Remove filter for status' }));
    preview();
    expect(screen.getByLabelText('Final filtered DSL')).toHaveValue(f.query.dsl);
    apply();
    expect(screen.getByLabelText('Query DSL')).toHaveValue(f.query.dsl);
    expect(screen.queryByRole('group', { name: '1 session filters' })).not.toBeInTheDocument();
    expect(screen.queryByRole('group', { name: '0 pending filters' })).not.toBeInTheDocument();
    expect(screen.getByRole('button', { name: 'Run query' })).toBeEnabled();
    expect(f.backend.execute).toHaveBeenCalledTimes(1);
    await f.saved();
  });
});
